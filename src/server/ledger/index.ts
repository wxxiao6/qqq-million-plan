function latestNavMap(): Record<string, NavSnapshot> {
  const rows = getDb()
    .prepare(
      `SELECT n.symbol, n.as_of AS asOf, n.nav, n.nav_change_pct AS navChangePct
       FROM nav_snapshots n
       INNER JOIN (
         SELECT symbol, MAX(as_of) AS as_of FROM nav_snapshots GROUP BY symbol
       ) latest ON n.symbol = latest.symbol AND n.as_of = latest.as_of`,
    )
    .all() as NavSnapshot[];
  const out: Record<string, NavSnapshot> = {};
  for (const row of rows) out[row.symbol] = row;
  return out;
}

/** 每个代码「最近净值日」之前的那一个净值。没有上一档则为空。 */
function priorNavMap(): Record<string, number> {
  const rows = getDb()
    .prepare(
      `SELECT symbol, as_of AS asOf, nav FROM nav_snapshots
       ORDER BY symbol, as_of DESC`,
    )
    .all() as NavSnapshot[];
  const seenLatest = new Set<string>();
  const out: Record<string, number> = {};
  for (const row of rows) {
    if (!seenLatest.has(row.symbol)) {
      seenLatest.add(row.symbol);
      continue;
    }
    if (out[row.symbol] == null) out[row.symbol] = row.nav;
  }
  return out;
}

function navForPosition(position: Position, snapshot: NavSnapshot | undefined): number | null {
  return snapshot && (!position.tDate || snapshot.asOf >= position.tDate) ? snapshot.nav : null;
}

function mapPosition(row: {
  id: number;
  account: Account;
  exposure: Exposure;
  symbol: string;
  shares: number | null;
  cost: number;
  status: PositionStatus;
  note: string | null;
  recorded_on: string | null;
  expected_confirm_on: string | null;
  dca_plan_id: number | null;
  cash_debited: number | null;
  fee_amount: number;
  t_nav: number | null;
  confirmed_on: string | null;
  execution_on: string | null;
  cutoff_period: CutoffPeriod | null;
  t_date: string | null;
  order_origin: "manual" | "dca" | null;
  closed_on: string | null;
  auto_generated?: number;
}): Position {
  return {
    id: row.id,
    account: row.account,
    exposure: row.exposure,
    symbol: row.symbol,
    shares: row.shares,
    cost: row.cost,
    status: row.status,
    note: row.note,
    recordedOn: row.recorded_on,
    expectedConfirmOn: row.expected_confirm_on,
    dcaPlanId: row.dca_plan_id,
    cashDebited: row.cash_debited ?? row.cost,
    feeAmount: row.fee_amount ?? 0,
    tNav: row.t_nav,
    confirmedOn: row.confirmed_on,
    executionOn: row.execution_on,
    cutoffPeriod: row.cutoff_period,
    tDate: row.t_date,
    orderOrigin: row.order_origin,
    closedOn: row.closed_on,
    autoGenerated: row.auto_generated === 1,
  };
}

export function listPositions(): Position[] {
  const rows = getDb()
    .prepare(
      `SELECT id, account, exposure, symbol, shares, cost, status, note, recorded_on, expected_confirm_on,
              dca_plan_id, cash_debited, fee_amount, t_nav, confirmed_on
              , execution_on, cutoff_period, t_date, order_origin, closed_on, auto_generated
       FROM positions ORDER BY id`,
    )
    .all() as Array<Parameters<typeof mapPosition>[0]>;
  return rows.map(mapPosition);
}

/** 持仓管理专用的逐笔估值；持仓概览不展开这些字段。 */
export function listPositionDetails(): PositionDetail[] {
  const navs = latestNavMap();
  const priors = priorNavMap();
  return listPositions().map((position) => {
    const snapshot = navs[position.symbol];
    const settled = position.status === "settled";
    const nav = navForPosition(position, snapshot);
    const marketValue = settled ? lotMarketValue(position.shares, nav) : null;
    return {
      ...position,
      nav,
      navAsOf: nav == null ? null : snapshot!.asOf,
      marketValue,
      holdingPnl: settled ? holdingGain(marketValue, position.cost) : null,
      today: settled && nav != null && (!position.tDate || snapshot!.asOf > position.tDate)
        ? lotDayPnl(
            position.shares,
            nav,
            verifiedPriorNav(snapshot, priors[position.symbol]),
          )
        : null,
    };
  });
}

