const PLATFORM_ORDER: Account[] = ["alipay", "cmb", "jd", "gf_direct", "other"];

function fundNameMap(): Record<string, string> {
  const rows = getDb()
    .prepare(
      `SELECT code AS symbol, name FROM nasdaq_funds ORDER BY share_class`,
    )
    .all() as Array<{ symbol: string; name: string }>;
  const out: Record<string, string> = {};
  for (const row of rows) {
    if (!out[row.symbol]) out[row.symbol] = row.name;
  }
  return out;
}

/** 公开源已给出日涨跌但本地尚未存到上一净值日时，反推上一日净值。 */
function priorNavFromChange(snapshot: NavSnapshot | undefined): number | null {
  const change = snapshot?.navChangePct;
  if (
    snapshot == null ||
    change == null ||
    !Number.isFinite(change) ||
    change <= -100
  ) {
    return null;
  }
  return snapshot.nav / (1 + change / 100);
}

/** Stored snapshots may skip trading days. Reject a stale baseline inconsistent with the published daily change. */
function verifiedPriorNav(snapshot: NavSnapshot | undefined, stored: number | undefined): number | null {
  const implied = priorNavFromChange(snapshot);
  if (stored == null) return implied;
  if (snapshot && implied != null && Math.abs(stored - implied) > snapshot.nav * 0.00005 + 0.0001) return implied;
  return stored;
}

/** 汇总与明细都以同一份「最新已披露净值日」收益计算。 */
function latestNavDayPnl(
  positions: Position[],
  navs: Record<string, NavSnapshot>,
  priors: Record<string, number>,
): number | null {
  return sumNullable(
    positions.map((row) => {
      const snapshot = navs[row.symbol];
      if (!snapshot || (row.tDate && snapshot.asOf <= row.tDate)) return null;
      return lotDayPnl(
        row.shares,
        snapshot?.nav ?? null,
        verifiedPriorNav(snapshot, priors[row.symbol]),
      );
    }),
  );
}

export function listNasdaqPlatformGroups(): NasdaqPlatformGroup[] {
  const navs = latestNavMap();
  const priors = priorNavMap();
  const names = fundNameMap();
  const lots = listPositions().filter((row) => row.exposure === "nasdaq" && (row.status === "settled" || row.status === "pending"));
  const byAccount = new Map<Account, NasdaqLotView[]>();
  for (const row of lots) {
    const list = byAccount.get(row.account) ?? [];
    const settled = row.status === "settled";
    const snapshot = navs[row.symbol];
    const nav = navForPosition(row, snapshot);
    const marketValue = settled ? lotMarketValue(row.shares, nav) : null;
    list.push({
      id: row.id,
      account: row.account,
      symbol: row.symbol,
      name: names[row.symbol] ?? null,
      shares: row.shares,
      cost: row.cost,
      marketValue,
      holdingPnl: settled ? holdingGain(marketValue, row.cost) : null,
      today: settled && snapshot && (!row.tDate || snapshot.asOf > row.tDate)
        ? lotDayPnl(
            row.shares,
            nav,
            verifiedPriorNav(snapshot, priors[row.symbol]),
          )
        : null,
      navAsOf: nav == null ? null : snapshot?.asOf ?? null,
      status: row.status,
    });
    byAccount.set(row.account, list);
  }

  return PLATFORM_ORDER.flatMap((account) => {
    const groupLots = byAccount.get(account);
    if (!groupLots || groupLots.length === 0) return [];
    const settled = groupLots.filter((lot) => lot.status === "settled");
    const marketValue = sumMarketValue(
      settled.map((lot) => ({
        shares: lot.shares,
        nav: navs[lot.symbol]?.nav ?? null,
      })),
    );
    const cost = settled.reduce((sum, lot) => sum + lot.cost, 0);
    const shares = settled.every((lot) => lot.shares == null)
      ? null
      : settled.reduce((sum, lot) => sum + (lot.shares ?? 0), 0);
    return [
      {
        account,
        lots: groupLots,
        shares,
        cost,
        marketValue,
        holdingPnl: holdingGain(marketValue, cost),
        today: sumNullable(settled.map((lot) => lot.today)),
      },
    ];
  });
}

export function getDynamicMarketValue(asOf?: string): number | null {
  return sumNullable(
    (["nasdaq", "gold", "crypto"] as Exposure[]).map(
      (exposure) => getExposureSummary(exposure, asOf).marketValue,
    ),
  );
}

export function hasDynamicSettled(): boolean {
  return (["nasdaq", "gold", "crypto"] as Exposure[]).some(
    (exposure) => getExposureSummary(exposure).hasSettled,
  );
}

export function upsertTodaySnapshot() {
  const day = beijingTodayISO();
  const marketValue = getDynamicMarketValue(day);
  if (marketValue == null) return;
  getDb()
    .prepare(
      `INSERT INTO portfolio_snapshots (as_of, dynamic_mv) VALUES (?, ?)
       ON CONFLICT(as_of) DO UPDATE SET dynamic_mv = excluded.dynamic_mv`,
    )
    .run(day, marketValue);
}

