export function writeAutoNav(symbol: string, asOf: string, nav: number) {
  const existing = getDb()
    .prepare("SELECT source FROM nav_snapshots WHERE symbol = ? AND as_of = ?")
    .get(symbol, asOf) as { source: string | null } | undefined;
  if (existing?.source === "manual") return;
  getDb()
    .prepare(
      `INSERT INTO nav_snapshots (symbol, as_of, nav, source) VALUES (?, ?, ?, 'auto')
       ON CONFLICT(symbol, as_of) DO UPDATE SET nav = excluded.nav, source = 'auto'`,
    )
    .run(symbol, asOf, nav);
}

