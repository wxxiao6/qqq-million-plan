import { mkdtempSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

let dir: string;
beforeEach(() => {
  dir = mkdtempSync(path.join(os.tmpdir(), 'recent-pending-'));
  vi.stubEnv('P0_TEST_DB', path.join(dir, 'ledger.sqlite'));
  vi.resetModules();
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(new Date('2026-10-10T04:00:00Z'));
});
afterEach(() => { vi.useRealTimers(); vi.unstubAllEnvs(); rmSync(dir, { recursive: true, force: true }); });

const plan = { symbol: '019547', shareClass: 'A', channelKind: 'agency', account: 'alipay',
  amount: 10, frequency: 'daily', startDate: '2026-10-08', cutoffPeriod: 'before_15' as const };
const history = [{ asOf: '2026-10-09', nav: 2 }, { asOf: '2026-10-08', nav: 1.5 }, { asOf: '2026-09-30', nav: 1 }];

async function setup() {
  const { getDb } = await import('./db');
  const { saveRecentNavHistory, importPastPlanPending } = await import('./ledger/recent-pending');
  const { upsertDcaPlan, listDcaPlans } = await import('./dca');
  const { listPositions, listPositionDetails } = await import('./ledger');
  saveRecentNavHistory(plan.symbol, history);
  return { db: getDb(), saveRecentNavHistory, importPastPlanPending, upsertDcaPlan, listDcaPlans, listPositions, listPositionDetails };
}

describe('过去起始日补录与雷达三日净值缓存', () => {
  it('10月10日录入8日起每日计划，自动生成8、9日两笔，下期12日且不重复', async () => {
    const ctx = await setup();
    const result = ctx.upsertDcaPlan(plan, { importPastPending: true });
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.error);
    expect(ctx.listPositions().map((p) => p.executionOn).sort()).toEqual(['2026-10-08', '2026-10-09']);
    expect(ctx.listPositions().every((p) => p.status === 'pending' && p.autoGenerated)).toBe(true);
    expect(ctx.listPositions().find((p) => p.executionOn === '2026-10-08')?.shares).toBe(6.67);
    expect(ctx.listPositionDetails().every((p) => p.marketValue == null && p.today == null)).toBe(true);
    expect(ctx.listDcaPlans()[0]).toMatchObject({ nextDebitDate: '2026-10-12', investedTotal: 20 });
    ctx.importPastPlanPending(result.id);
    ctx.upsertDcaPlan({ ...plan, id: result.id, amount: 20 }, { importPastPending: true });
    expect(ctx.listPositions()).toHaveLength(2);
  });
  it('9日起只补9日，8日起补8、9日，补录范围不受三条净值缓存限制', async () => {
    const ctx = await setup();
    expect(ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-09' }, { importPastPending: true }).ok).toBe(true);
    expect(ctx.listPositions().map((p) => p.executionOn)).toEqual(['2026-10-09']);
    const older = ctx.upsertDcaPlan({ ...plan, account: 'jd', startDate: '2026-09-29' }, { importPastPending: true });
    expect(older.ok).toBe(true);
    if (!older.ok) throw new Error(older.error);
    const rows = ctx.listPositions().filter((p) => p.dcaPlanId === older.id);
    expect(rows.some((p) => p.executionOn === '2026-09-29')).toBe(true);
    // 更早缓存缺失不能把9月30日净值冒充9月29日成交净值。
    expect(rows.find((p) => p.executionOn === '2026-09-29')?.shares).toBeNull();
  });
  it('雷达缓存缺失属于数据异常，整个保存回滚', async () => {
    const { upsertDcaPlan, listDcaPlans } = await import('./dca');
    const { listPositions } = await import('./ledger');
    const result = upsertDcaPlan(plan, { importPastPending: true });
    expect(result).toMatchObject({ ok: false, error: expect.stringContaining('纳指雷达净值数据异常') });
    expect(listDcaPlans()).toHaveLength(0);
    expect(listPositions()).toHaveLength(0);
  });
  it('创建时记账至今天，未来期次不提前记账', async () => {
    const ctx = await setup();
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    expect(ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12' }, { importPastPending: true }).ok).toBe(true);
    expect(ctx.upsertDcaPlan({ ...plan, account: 'cmb', startDate: '2026-10-13' }, { importPastPending: true }).ok).toBe(true);
    expect(ctx.listPositions().map((p) => p.executionOn)).toEqual(['2026-10-12']);
    const past = ctx.upsertDcaPlan({ ...plan, account: 'jd', startDate: '2026-10-09' }, { importPastPending: true });
    if (!past.ok) throw new Error(past.error);
    expect(ctx.listPositions().filter((p) => p.dcaPlanId === past.id).map((p) => p.executionOn)).toEqual(['2026-10-09', '2026-10-12']);
    expect(ctx.listDcaPlans().find((p) => p.id === past.id)?.nextDebitDate).toBe('2026-10-13');
  });
  it('15点后用下一净值日，尚未公布保留无份额在途，刷新补齐并按窗口结转同一笔', async () => {
    const ctx = await setup();
    const result = ctx.upsertDcaPlan({ ...plan, cutoffPeriod: 'after_15', feeKind: 'fixed', feeValue: 1 }, { importPastPending: true });
    expect(result.ok).toBe(true);
    const initial = ctx.listPositions();
    expect(initial.find((p) => p.executionOn === '2026-10-08')).toMatchObject({ tDate: '2026-10-09', shares: 4.5, cost: 9 });
    const last = initial.find((p) => p.executionOn === '2026-10-09')!;
    expect(last.shares).toBeNull();
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    ctx.saveRecentNavHistory(plan.symbol, [{ asOf: '2026-10-12', nav: 3 }, ...history.slice(0, 2)]);
    expect(ctx.listPositions().find((p) => p.id === last.id)).toMatchObject({ tDate: '2026-10-12', shares: 3, status: 'pending' });
    vi.setSystemTime(new Date('2026-10-15T04:00:00Z'));
    ctx.saveRecentNavHistory(plan.symbol, [{ asOf: '2026-10-15', nav: 4 }, { asOf: '2026-10-14', nav: 3.8 }, { asOf: '2026-10-13', nav: 3.5 }]);
    expect(ctx.listPositions().find((p) => p.id === last.id)).toMatchObject({ status: 'settled', shares: 3 });
    expect(ctx.listPositions()).toHaveLength(2);
  });
  it('未来计划的手续费不合法时保存即报错，而不是等到计划日', async () => {
    const ctx = await setup();
    const result = ctx.upsertDcaPlan({ ...plan, startDate: '2026-11-02', feeKind: 'fixed', feeValue: 10 }, { importPastPending: true });
    expect(result).toMatchObject({ ok: false, error: '手续费不能大于等于定投金额' });
    expect(ctx.listPositions()).toHaveLength(0);
  });
  it('补录失败时整体回滚，不能留下计划或部分在途', async () => {
    await setup();
    const { upsertDcaPlan } = await import('./dca');
    const { getDb } = await import('./db');
    expect(upsertDcaPlan({ ...plan, feeKind: 'fixed', feeValue: 20 }, { importPastPending: true }).ok).toBe(false);
    expect(getDb().prepare('SELECT COUNT(*) AS n FROM dca_plans').get()).toEqual({ n: 0 });
    expect(getDb().prepare('SELECT COUNT(*) AS n FROM positions').get()).toEqual({ n: 0 });
  });
});


describe('按期自动记账', () => {
  it('修改购买账户同步历史扣款与持仓，并用于后续期次', async () => {
    const ctx = await setup();
    const { reconcileDueDcaPlans } = await import('./ledger/recent-pending');
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    const saved = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12' }, { importPastPending: true });
    if (!saved.ok) throw new Error(saved.error);
    expect(ctx.listPositions()).toMatchObject([{ executionOn: '2026-10-12', account: 'alipay' }]);
    const updated = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12', id: saved.id, account: 'jd' }, { importPastPending: false });
    expect(updated.ok).toBe(true);
    expect(ctx.listDcaPlans()[0]).toMatchObject({ id: saved.id, account: 'jd', investedTotal: 10 });
    expect(ctx.listPositions()).toMatchObject([{ executionOn: '2026-10-12', account: 'jd', cost: 10, status: 'pending' }]);
    const changedFund = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12', id: saved.id, account: 'jd', symbol: '016452' }, { importPastPending: false });
    expect(changedFund).toMatchObject({ ok: false, error: '已有扣款记录的计划不可修改基金或份额' });
    vi.setSystemTime(new Date('2026-10-13T04:00:00Z'));
    expect(reconcileDueDcaPlans()).toEqual([]);
    expect(ctx.listPositions().map((position) => ({ executionOn: position.executionOn, account: position.account })))
      .toEqual([{ executionOn: '2026-10-12', account: 'jd' }, { executionOn: '2026-10-13', account: 'jd' }]);
    expect(ctx.listDcaPlans()[0].investedTotal).toBe(20);
  });
  it('迁移已确认持仓的账户时保留其他持仓', async () => {
    const ctx = await setup();
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    const saved = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12' }, { importPastPending: true });
    if (!saved.ok) throw new Error(saved.error);
    ctx.db.prepare("UPDATE positions SET status='settled', shares=10, t_date='2026-10-09', recorded_on='2026-10-09' WHERE dca_plan_id=?").run(saved.id);
    ctx.db.prepare("INSERT INTO positions (account, exposure, symbol, shares, cost, status, recorded_on, updated_at) VALUES ('alipay', 'nasdaq', ?, 5, 10, 'settled', '2026-10-09', '2026-10-12')").run(plan.symbol);
    expect(ctx.upsertDcaPlan({ ...plan, id: saved.id, startDate: '2026-10-12', account: 'jd' }, { importPastPending: false }).ok).toBe(true);
    expect(ctx.listPositions().map((p) => p.account)).toEqual(['jd', 'alipay']);
  });
  it('再次保存可修复计划与旧记录账户不一致，保留其他计划的记录', async () => {
    const ctx = await setup();
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    const saved = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12', account: 'jd' }, { importPastPending: true });
    const other = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12' }, { importPastPending: true });
    if (!saved.ok || !other.ok) throw new Error('计划创建失败');
    ctx.db.prepare("UPDATE positions SET account='alipay' WHERE dca_plan_id=?").run(saved.id);
    expect(ctx.upsertDcaPlan({ ...plan, id: saved.id, startDate: '2026-10-12', account: 'jd' }, { importPastPending: false }).ok).toBe(true);
    expect(ctx.listPositions().map((p) => ({ planId: p.dcaPlanId, account: p.account }))).toEqual([
      { planId: saved.id, account: 'jd' }, { planId: other.id, account: 'alipay' },
    ]);
  });
  it('创建当天记账，补齐停机期间且重复同步不重复；暂停期间不补记', async () => {
    const ctx = await setup();
    const { reconcileDueDcaPlans } = await import('./ledger/recent-pending');
    const { setDcaPlanStatus, correctDcaExecution, listDcaExecutionHistory } = await import('./dca');
    vi.setSystemTime(new Date('2026-10-12T04:00:00Z'));
    const saved = ctx.upsertDcaPlan({ ...plan, startDate: '2026-10-12' }, { importPastPending: true });
    if (!saved.ok) throw new Error(saved.error);
    expect(ctx.listPositions().map((p) => p.executionOn)).toEqual(['2026-10-12']);
    vi.setSystemTime(new Date('2026-10-14T04:00:00Z'));
    expect(reconcileDueDcaPlans()).toEqual([]);
    expect(reconcileDueDcaPlans()).toEqual([]);
    expect(ctx.listPositions().map((p) => p.executionOn)).toEqual(['2026-10-12', '2026-10-13', '2026-10-14']);
    expect(setDcaPlanStatus(saved.id, 'paused').ok).toBe(true);
    vi.setSystemTime(new Date('2026-10-19T04:00:00Z'));
    expect(reconcileDueDcaPlans()).toEqual([]);
    expect(setDcaPlanStatus(saved.id, 'active').ok).toBe(true);
    expect(ctx.listPositions().map((p) => p.executionOn)).toEqual(['2026-10-12', '2026-10-13', '2026-10-14', '2026-10-19']);
    const last = listDcaExecutionHistory().find((record) => record.executionOn === '2026-10-19')!;
    expect(correctDcaExecution({ id: last.positionId, cashDebited: 8, feeAmount: 1, outcome: 'keep' }).ok).toBe(true);
    expect(ctx.listPositions().find((p) => p.id === last.positionId)).toMatchObject({ cashDebited: 8, feeAmount: 1, cost: 7 });
    expect(correctDcaExecution({ id: last.positionId, cashDebited: 8, feeAmount: 1, outcome: 'failed' }).ok).toBe(true);
    expect(reconcileDueDcaPlans()).toEqual([]);
    expect(ctx.listPositions()).toHaveLength(4);
    expect(ctx.listDcaPlans()[0].investedTotal).toBe(30);
  });
});
